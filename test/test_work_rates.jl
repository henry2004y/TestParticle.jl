## --- Axisymmetric mirror built from a vector potential -----------------------
#
# A(x, t) = (B₀(t) g(z) / 2) (-y, x, 0) with g(z) = 1 + α z² generates
# B = ∇×A = B₀(t) (-α x z, -α y z, 1 + α z²), divergence free by construction.
# Taking E = -∂A/∂t - ∇Φ makes ∇×E = -∂B/∂t hold identically, so the pair is a
# genuine solution of Maxwell's equations rather than two unrelated prescriptions.

const B₀₀ = 1.0e-4    # [T]
const α = 1.0e-2      # [m⁻²]
const β = 0.1         # [1/s]
const Epar0 = 2.0e-5  # [V/m]
const L_E = 50.0      # [m]

B₀(t) = B₀₀ * (1 + β * t)
g_mirror(z) = 1 + α * z^2

function mirror_B(x, t = 0.0)
    B0t = B₀(t)
    return SA[-B0t * α * x[1] * x[3], -B0t * α * x[2] * x[3], B0t * g_mirror(x[3])]
end

"""
    mirror_E(x, t)

Inductive field `-∂A/∂t` plus a parallel component `-∇Φ` generated by
`Φ = -Epar0 (z + z² / (2 L_E))`. The potential part is curl free, so it adds `E∥`
without disturbing Faraday's law.
"""
function mirror_E(x, t = 0.0)
    c = B₀₀ * β * g_mirror(x[3]) / 2
    return SA[c * x[2], -c * x[1], Epar0 * (1 + x[3] / L_E)]
end

"Uniform field growing in time, together with the electric field it induces."
uniform_Bt(x, t) = SA[0.0, 0.0, B₀(t)]

function uniform_Et(x, t)
    c = B₀₀ * β / 2
    return SA[c * x[2], -c * x[1], 0.0]
end

"Static mirror: same geometry as [`mirror_B`](@ref) but frozen in time."
mirror_B_static(x, t) = mirror_B(x, 0.0)

E_zero(x, t) = SA[0.0, 0.0, 0.0]

## --- Helper ------------------------------------------------------------------

"""
    gc_energy_derivative(y, p, t)

`dK/dt` for `K = ½ m v∥² + μ B` along the guiding-center trajectory, assembled
from the very right-hand side that `trace_gc!` integrates, without any time
integration in between.
"""
function gc_energy_derivative(y, p, t)
    q, q2m, μ, _, Bfunc = p
    m = q / q2m
    X = SA[y[1], y[2], y[3]]
    v1, v2, v3, du = TP.get_gc_derivatives(y, p, t)
    _, ∇B, _, b̂, _ = TP.get_magnetic_properties(X, t, Bfunc)
    dBdt_local = TP.derivative_t(Bfunc, X, t) ⋅ b̂

    return m * y[4] * du + μ * (dBdt_local + SA[v1, v2, v3] ⋅ ∇B)
end

"Curl of a field from its Jacobian `J`, with `J[i, j] = ∂f_i/∂x_j`."
curl_from_jacobian(J) = SA[J[3, 2] - J[2, 3], J[1, 3] - J[3, 1], J[2, 1] - J[1, 2]]

@testset "Work rates" begin
    @testset "vector-potential fields satisfy Maxwell" begin
        x = SA[3.0, -2.0, 5.0]
        t = 0.3

        # ∇ ⋅ B = 0
        JB = TP.jacobian(TP.Field(mirror_B), x, t)
        @test tr(JB) ≈ 0.0 atol = 1.0e-14

        # ∇ × E = -∂B/∂t
        JE = TP.jacobian(TP.Field(mirror_E), x, t)
        @test curl_from_jacobian(JE) ≈ -TP.derivative_t(TP.Field(mirror_B), x, t) rtol = 1.0e-10

        # Same check for the uniform growing field
        @test curl_from_jacobian(TP.jacobian(TP.Field(uniform_Et), x, t)) ≈
            -TP.derivative_t(TP.Field(uniform_Bt), x, t) rtol = 1.0e-10
    end

    @testset "grad-B drift work is the convective part of betatron" begin
        x = SA[3.0, -2.0, 5.0]
        t = 0.3
        Bf, Ef = TP.Field(mirror_B), TP.Field(mirror_E)
        _, ∇B, _, b̂, Bmag = TP.get_magnetic_properties(x, t, Bf)
        E = Ef(x, t)
        μ = 1.0e-15
        p = (; q = TP.qᵢ, q2m = TP.qᵢ / TP.mᵢ, μ, E = Ef, B = Bf)
        y = SA[x[1], x[2], x[3], 1.0e4]

        wr = TP.get_work_rates_gc(y, p, t)
        v_E = (E × b̂) / Bmag

        @test wr[3] ≈ μ * (v_E ⋅ ∇B) rtol = 1.0e-12
    end

    @testset "four terms sum to dK/dt in an axisymmetric field" begin
        # Axisymmetric with B_φ = 0 ⇒ b̂ ⋅ (∇×b̂) = 0 ⇒ B*_∥ = |B|, and the
        # decomposition is exact rather than O(ε) accurate.
        Bf, Ef = TP.Field(mirror_B), TP.Field(mirror_E)
        state_gc, p = TP.prepare_gc(
            [8.0, 4.0, 3.0, 4.0e4, -2.0e4, 3.0e4], Ef, Bf; species = TP.Proton
        )
        μ = p.μ
        @test μ > 0

        states = (
            SA[8.0, 4.0, 3.0, 3.0e4],
            SA[8.0, 4.0, 3.0, -3.0e4],
            SA[-2.0, 6.0, -7.0, -1.5e4],
            SA[0.5, 0.0, 10.0, 5.0e4],
        )
        for t in (0.0, 0.4, 1.2), y in states
            dKdt = gc_energy_derivative(y, p, t)
            @test sum(TP.get_work_rates_gc(y, p, t)) ≈ dKdt rtol = 1.0e-8
        end
    end

    @testset "precomputed properties reproduce the work rates" begin
        x = SA[3.0, -2.0, 5.0]
        t = 0.3
        Bf, Ef = TP.Field(mirror_B), TP.Field(mirror_E)
        _, p = TP.prepare_gc([8.0, 4.0, 3.0, 4.0e4, -2.0e4, 3.0e4], Ef, Bf; species = TP.Proton)
        y = SA[x[1], x[2], x[3], 2.0e4]

        mp = TP.get_magnetic_properties(x, t, Bf)
        ref = TP.get_work_rates_gc(y, p, t)
        @test TP.get_work_rates_gc(y, p, t, mp) == ref
        @test TP.get_work_rates_gc(y, p, t, mp, Ef(x, t)) == ref
    end

    @testset "channel grouping merges grad-B into betatron" begin
        x = SA[3.0, -2.0, 5.0]
        t = 0.3
        Bf, Ef = TP.Field(mirror_B), TP.Field(mirror_E)
        _, p = TP.prepare_gc([8.0, 4.0, 3.0, 4.0e4, -2.0e4, 3.0e4], Ef, Bf; species = TP.Proton)
        y = SA[x[1], x[2], x[3], 2.0e4]

        wr = TP.get_work_rates_gc(y, p, t)
        ch = TP.get_work_channels(y, p, t)

        @test ch[1] == wr[1]
        @test ch[2] == wr[2]
        @test ch[3] ≈ wr[3] + wr[4]
        @test sum(ch) ≈ sum(wr)

        # A full-orbit parameter tuple carries the E field in slot 3, which selects
        # the full-orbit flavor.
        state_fo = SA[x[1], x[2], x[3], 4.0e4, -2.0e4, 3.0e4]
        p_fo = (; q2m = TP.qᵢ / TP.mᵢ, m = TP.mᵢ, E = Ef, B = Bf, F = nothing)
        @test sum(TP.get_work_channels(state_fo, p_fo, t)) ≈
            sum(TP.get_work_rates(state_fo, p_fo, t))
    end

    @testset "channels of a diagnostic-enabled guiding-center state" begin
        # `save_fields`/`save_work` append 6 + 4 diagnostics to every saved state, so
        # the flavor must come from the parameter layout, not from `length(xv)`.
        Bf, Ef = TP.Field(mirror_B), TP.Field(mirror_E)
        state_gc, p = TP.prepare_gc(
            [8.0, 4.0, 3.0, 4.0e4, -2.0e4, 3.0e4], Ef, Bf; species = TP.Proton
        )
        sol = solve(
            TraceGCProblem(state_gc, (0.0, 1.0e-6), p);
            dt = 1.0e-8, save_fields = true, save_work = true
        )
        traj = sol.u[1]
        y = traj.u[end]
        @test length(y) == 14

        t = traj.t[end]
        y4 = SA[y[1], y[2], y[3], y[4]]
        @test TP.get_work_channels(y, p, t) == TP.get_work_channels(y4, p, t)

        wr = TP.get_work_rates_gc(y4, p, t)
        @test SA[y[11], y[12], y[13], y[14]] ≈ wr rtol = 1.0e-12
        @test TP.get_work_channels(y, p, t) == SA[wr[1], wr[2], wr[3] + wr[4]]
    end

    @testset "static field with E = 0 does no work" begin
        Bf, Ef = TP.Field(mirror_B_static), TP.Field(E_zero)
        state_gc, p = TP.prepare_gc(
            [8.0, 4.0, 3.0, 4.0e4, -2.0e4, 3.0e4], Ef, Bf; species = TP.Proton
        )
        y = SA[state_gc[1], state_gc[2], state_gc[3], state_gc[4]]

        for t in (0.0, 0.7)
            @test all(abs.(TP.get_work_rates_gc(y, p, t)) .< 1.0e-30)
            @test abs(gc_energy_derivative(y, p, t)) < 1.0e-30
        end
    end

    @testset "pure betatron: uniform B(t) with the induced E" begin
        Bf, Ef = TP.Field(uniform_Bt), TP.Field(uniform_Et)
        state_gc, p = TP.prepare_gc(
            [0.0, 0.0, 0.0, 3.0e4, 0.0, 1.0e4], Ef, Bf; species = TP.Proton
        )
        q, q2m, μ, _, _ = p
        m = q / q2m
        y = SA[state_gc[1], state_gc[2], state_gc[3], state_gc[4]]

        # κ = 0 and ∇B = 0 kill Fermi and grad-B; E ⟂ b̂ kills the parallel term.
        wr = TP.get_work_rates_gc(y, p, 0.0)
        @test abs(wr[1]) < 1.0e-30
        @test abs(wr[2]) < 1.0e-30
        @test abs(wr[3]) < 1.0e-30
        @test wr[4] ≈ μ * B₀₀ * β

        # v∥ stays put and the whole energy gain is μ ΔB.
        tspan = (0.0, 2.0)
        prob = ODEProblem(TP.trace_gc!, state_gc, tspan, p)
        sol = solve(prob, Vern9(); save_everystep = false)
        K_gc(t, u) = 0.5 * m * u[4]^2 + μ * B₀(t)
        ΔK = K_gc(tspan[2], sol.u[end]) - K_gc(tspan[1], sol.u[1])

        @test sol.u[end][4] ≈ sol.u[1][4] rtol = 1.0e-10
        @test ΔK ≈ μ * (B₀(tspan[2]) - B₀(tspan[1])) rtol = 1.0e-8
    end

    @testset "full orbit recovers betatron in a uniform B(t)" begin
        # Same physics integrated with the Boris pusher: the gyro-averaged work
        # rates must match the guiding-center prediction.
        stateinit = [0.0, 0.0, 0.0, 3.0e4, 0.0, 1.0e4]
        param = TP.prepare(uniform_Et, uniform_Bt; species = TP.Proton)
        μ₀ = TP.mᵢ * (3.0e4^2) / (2 * B₀₀)
        gyroperiod = 2π * TP.mᵢ / (TP.qᵢ * B₀₀)
        dt = gyroperiod / 200

        prob = TP.TraceProblem(stateinit, (0.0, 15 * gyroperiod), param)
        sol = solve(prob, TP.Boris(); dt, save_everystep = true)

        rates = reduce(hcat, TP.get_work(sol))
        P_par, P_fermi, P_grad, P_betatron = eachrow(rates)

        # Uniform field: the three non-betatron terms vanish identically.
        @test maximum(abs, P_par) < 1.0e-30
        @test maximum(abs, P_fermi) < 1.0e-30
        @test maximum(abs, P_grad) < 1.0e-30

        # μ is adiabatically conserved, so μ ∂B/∂t is a constant power input.
        @test sum(P_betatron) / length(P_betatron) ≈ μ₀ * B₀₀ * β rtol = 0.05
    end

    @testset "guiding center conserves energy in a static bottle" begin
        # `bottle_B` from the shared fixtures is the same axisymmetric mirror,
        # frozen in time, so tracing it with E = 0 must leave K untouched.
        Bf, Ef = TP.Field(bottle_B), TP.Field(E_zero)
        state_gc, p = TP.prepare_gc(
            [5.0, 0.0, 2.0, 2.0e4, 1.0e4, 4.0e4], Ef, Bf; species = TP.Proton
        )
        q, q2m, μ, _, _ = p
        m = q / q2m

        prob = ODEProblem(TP.trace_gc!, state_gc, (0.0, 1.0e-3), p)
        sol = solve(prob, Vern9())
        X_end = SA[sol.u[end][1], sol.u[end][2], sol.u[end][3]]
        K_end = 0.5 * m * sol.u[end][4]^2 + μ * norm(Bf(X_end, 0.0))
        K_start = 0.5 * m * state_gc[4]^2 + μ * norm(Bf(SA[state_gc[1], state_gc[2], state_gc[3]], 0.0))

        @test K_end ≈ K_start rtol = 1.0e-8
    end
end

end # module test_work_rates
